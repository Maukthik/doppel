def hook_files() -> dict[str, bytes]:
    return {"sitecustomize.py": SITECUSTOMIZE.encode(), f"{RECORDER_MODULE}.py": RECORDER.read_bytes(),
            f"{PLUGIN}.py": PLUGIN_SOURCE.encode()}


ENV_ASSIGN = re.compile(r"""^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=("[^"]*"|'[^']*'|[^\s;&]*)\s*(?:;|&&)?\s*""")


def split_env(cmd: str) -> tuple[dict, str]:
    """`export PYTHONPATH=./docs_src; pytest tests` -> ({"PYTHONPATH": "./docs_src"}, "pytest tests"). The
    settings go into every world's environment (PYTHONPATH joined, never replacing Doppel's recorder path);
    only the command itself is split into shards or narrowed for confirmation."""
    env: dict[str, str] = {}
    rest = cmd
    while (m := ENV_ASSIGN.match(rest)) and m.group(0).strip():
        value = m.group(2)
        env[m.group(1)] = value[1:-1] if value[:1] in "\"'" and value[-1:] == value[:1] and len(value) > 1 else value
        rest = rest[m.end():]
    return env, rest.strip()


def world_env(hook_dir: str, out_dir: str, base_env: dict | None = None, sep: str = os.pathsep,
              extra: dict | None = None) -> dict:
    """S3: the same deterministic environment in every world. `sep` is the PYTHONPATH separator of the
    machine the tests run on (":" in a Linux sandbox, even when Doppel itself runs on Windows)."""
    # nothing a parent test run set may leak in: PYTEST_CURRENT_TEST from an outer pytest made the recorder
    # credit every request to the wrong test and skip unittest outcomes (Django's runner)
    env = {k: v for k, v in (base_env or {}).items()
           if not k.startswith(("PYTEST_", "DOPPEL_TRAFFIC", "COV_CORE_")) and k not in ("PYTHONHASHSEED",)}
    env["PYTHONPATH"] = hook_dir + (sep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
    env["DOPPEL_TRAFFIC_OUT"] = out_dir
    env["PYTEST_PLUGINS"] = PLUGIN
    env["PYTEST_ADDOPTS"] = "-p no:randomly -p no:cacheprovider"
    env["PYTHONHASHSEED"] = "0"
    env["TZ"] = "UTC"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    for k, v in (extra or {}).items():   # the project's own settings (from its test script or doppel.toml)
        if k == "PYTHONPATH":
            env["PYTHONPATH"] = hook_dir + sep + v.replace("$PYTHONPATH", "").strip(sep) + (
                sep + base_env["PYTHONPATH"] if (base_env or {}).get("PYTHONPATH") else "")
        else:
            env[k] = v
    return env


# ---------------------------------------------------------------- 3. running the worlds

def _changed_files(base: Path, head: Path) -> tuple[list[str], list[str]]:
    """(changed or added in head, removed in head), app-relative posix paths."""
    def files(root: Path) -> dict[str, bytes]:
        out = {}
        for p in root.rglob("*"):
            rel = p.relative_to(root)
            if p.is_file() and not {".git", "__pycache__", ".tox", ".venv", "venv", "node_modules"} & set(rel.parts):
                out[rel.as_posix()] = p.read_bytes()
        return out
    b, h = files(base), files(head)
    return sorted(k for k in h if b.get(k) != h[k]), sorted(k for k in b if k not in h)


TEST_FILE = re.compile(r"(^|/)(tests?|testing)/|(^|/)(test_[^/]*|[^/]*_test|conftest)\.py$")


def is_test_file(rel: str) -> bool:
    """Files that belong to the test suite rather than the app (tests/, test_*.py, *_test.py, conftest.py)."""
    return bool(TEST_FILE.search(rel))


def head_with_base_tests(base: Path, head: Path, dest: Path) -> None:
    """The head world: the PR's app code with the BASE branch's tests. The same tests (the same users)
    run against both versions, so a PR cannot hide a behavior change by editing the test that shows it."""
    shutil.copytree(head, dest, ignore=SKIP)
    for p in list(dest.rglob("*")):
        rel = p.relative_to(dest).as_posix()
        if p.is_file() and is_test_file(rel) and not (base / rel).exists():
            p.unlink()                                  # a test the PR added: no baseline to compare against
    for p in base.rglob("*"):
        rel = p.relative_to(base).as_posix()
        if p.is_file() and is_test_file(rel) and not {".git", "__pycache__"} & set(p.relative_to(base).parts):
            target = dest / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, target)


DEPENDENCY_FILES = re.compile(r"(^|/)(requirements[^/]*\.txt|pyproject\.toml|setup\.py|setup\.cfg|tox\.ini|Pipfile)$")


class LocalSession:
    """The worlds as folders in your current Python environment. Every job runs in a fresh copy of its code
    (tests may write files), all jobs of a batch at the same time."""

    def __init__(self, base: Path, head: Path, install: str = "", log=lambda m: None, python: str = "",
                 extra_env: dict | None = None, workdir: str = ""):
        self.extra_env = dict(extra_env or {})
        self.workdir = workdir
        self.add_env = self.extra_env.update     # a repair between tries (placeholder settings)
        # absolute(), not resolve(): a venv's python is a symlink to the base interpreter, and resolving it
        # would drop the venv (and everything installed in it)
        self.path_prefix = str(Path(python).absolute().parent) if python and Path(python).exists() else ""
        self.tmp = Path(tempfile.mkdtemp(prefix="doppel-tests-"))
        self.hook = self.tmp / "hook"
        self.hook.mkdir()
        for name, data in hook_files().items():
            (self.hook / name).write_bytes(data)
        self.code = {"base": self.tmp / "code-base", "head": self.tmp / "code-head"}
        shutil.copytree(base, self.code["base"], ignore=SKIP)
        head_with_base_tests(base, head, self.code["head"])
        self.n = 0

    def run(self, jobs: list[tuple[str, str]], timeout: int = TEST_TIMEOUT) -> list[dict]:
        """jobs: [(code "base"|"head", command)] -> one {file name: text} per job, same order."""
        dirs = []
        for code, _ in jobs:
            self.n += 1
            work, out = self.tmp / f"job{self.n}", self.tmp / f"out{self.n}"
            shutil.copytree(self.code[code], work)
            out.mkdir()
            dirs.append((work, out))
        threads = [threading.Thread(target=_run_one, args=(work / self.workdir if self.workdir else work, out,
                                                           self.hook, cmd, timeout, self.path_prefix,
                                                           self.extra_env))
                   for (work, out), (_, cmd) in zip(dirs, jobs, strict=True)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()
        results = [_collect(out) for _, out in dirs]
        for work, out in dirs:
            shutil.rmtree(work, ignore_errors=True)
            shutil.rmtree(out, ignore_errors=True)
        return results

    def close(self) -> None:
        shutil.rmtree(self.tmp, ignore_errors=True)


def _run_one(work: Path, out: Path, hook: Path, test: str, timeout: int, path_prefix: str = "",
             extra_env: dict | None = None) -> None:
    env = world_env(str(hook), str(out), dict(os.environ), extra=extra_env)
    if path_prefix:   # `python` in the test command is the interpreter (and its venv) the user chose
        env["PATH"] = path_prefix + os.pathsep + env.get("PATH", "")
        env["VIRTUAL_ENV"] = str(Path(path_prefix).parent)
    kw = {"start_new_session": True} if os.name != "nt" else {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP}
    with open(out / "output.txt", "w", encoding="utf-8", errors="replace") as f:
        p = subprocess.Popen(test, shell=True, cwd=work, env=env, stdout=f, stderr=subprocess.STDOUT, **kw)
        try:
            rc = p.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            rc = "timeout"
        finally:
            _kill_tree(p)
    (out / "exit").write_text(str(rc), encoding="utf-8")


def _kill_tree(p: subprocess.Popen) -> None:
    try:
        if os.name == "nt":
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(p.pid)], capture_output=True)
        else:
            import signal
            os.killpg(p.pid, signal.SIGKILL)
    except (OSError, ProcessLookupError):
        pass


def _collect(out: Path) -> dict:
    return {p.name: p.read_text("utf-8", errors="replace") for p in out.iterdir() if p.is_file()}


class NebiusSession:
    """Install once into a Nebius checkpoint, derive the head checkpoint from it, then run any batch of jobs,
    each a disposable fork, all at the same time."""

    def __init__(self, base: Path, head: Path, install: str = "", image: str = "", log=lambda m: None,
                 extra_env: dict | None = None, python: str = "", workdir: str = ""):
        import asyncio
        import shlex

        from doppel.backends.nebius import APP, code_files, make_client
        from doppel.probe import IMAGE, image_for
        code = base / workdir if workdir else base
        if not python and image_for(code) != IMAGE:   # the app declares another Python (requires-python)
            python = image_for(code).split(":")[1].split("-")[0]
            log(f"[tests] the app needs Python {python}: it will be installed in the sandbox")
        self.loop = asyncio.new_event_loop()
        self.log, self.app = log, f"{APP}/{workdir}" if workdir else APP
        changed, removed = _changed_files(base, head)
        changed = [c for c in changed if not is_test_file(c)]   # head world: the PR's code, the base's tests
        removed = [r for r in removed if not is_test_file(r)]
        sandbox_env = world_env("/doppel/hook", "/tmp/dt", {}, ":", extra=extra_env)
        # another Python than the image's: installed inside the sandbox with uv, into a venv every job uses (the
        # platform need not offer a python:X.Y image; asking for one it lacks fails to start the sandbox)
        self.venv = PYTHON_VENV if python and PYTHON_VERSION.match(python) else ""
        activate = f"export VIRTUAL_ENV={self.venv}; export PATH={self.venv}/bin:$PATH; " if self.venv else ""
        self.exports = activate + "".join(f"export {k}={shlex.quote(v)}; " for k, v in sandbox_env.items())
        self._activate = activate
        provision = (f"pip install --quiet uv && uv python install {python} && "
                     f"uv venv --quiet --seed -p {python} {self.venv} && {activate}") if self.venv else ""
        self.files = {f"doppel/hook/{n}": d for n, d in hook_files().items()}

        from doppel import sandbox
        self.sandbox, self.log = sandbox, log
        self.sem = sandbox.throttle()

        async def install_on(img, what: str, again: bool = False):
            """The install step: git first when needed; if it fails for want of a compiler or headers, once
            more with the build tools. Returns the installed image, or raises NotComparable with the output."""
            shell = sandbox.install_shell(install or "true", code)
            setup = "" if again else provision
            out = await sandbox.retrying(lambda: img.run(shell=f"cd {self.app} && {setup}{activate}{shell}",
                                                         disposable=False, timeout=TEST_TIMEOUT), what, log)
            text = (out.stdout or "") + (out.stderr or "")
            if out.exit_code != 0 and sandbox.needs_build_tools(text):
                log(f"[tests] {what} needs a compiler or system libraries: installing build tools, trying again")
                out = await sandbox.retrying(lambda: img.run(
                    shell=f"cd {self.app} && {setup}{activate}{sandbox.with_build_tools(shell)}", disposable=False,
                    timeout=TEST_TIMEOUT), what + " (with build tools)", log)
                text = (out.stdout or "") + (out.stderr or "")
                if out.exit_code != 0 and (pkgs := sandbox.header_packages(text)):
                    log(f"[tests] the build needs more system headers: installing {' '.join(pkgs)}, trying again")
                    extra = f"{sandbox.APT} install -y -qq --no-install-recommends {' '.join(pkgs)} >/dev/null 2>&1"
                    out = await sandbox.retrying(lambda: img.run(
                        shell=f"cd {self.app} && {setup}{activate}{sandbox.with_build_tools(extra + ' && ' + shell)}",
                        disposable=False, timeout=TEST_TIMEOUT), what + " (with more headers)", log)
                    text = (out.stdout or "") + (out.stderr or "")
            if out.exit_code != 0:
                raise NotComparable(f"{what} failed:\n" + text[-3000:])
            return out

        async def build():
            client = make_client()
            img = await sandbox.retrying(lambda: client.images.use(image or IMAGE), "starting the sandbox", log)
            from doppel.backends.nebius import left_out_summary
            if skipped := left_out_summary(base):
                log(f"[sandbox] left out of the upload: {skipped}")
            img = await sandbox.upload(img, code_files(base), "uploading the code", log)
            if provision:
                log(f"[tests] installing Python {python} in the sandbox (uv)")
            if install or provision:
                log(f"[tests] installing once: {install[:120]}")
                img = await install_on(img, "the install command")
            head_files = {k: v for k, v in code_files(head).items() if k.split("/", 1)[-1] in set(changed)}
            head_img = img
            if head_files:
                head_img = await sandbox.upload(img, head_files, "uploading the PR's code", log)
            if removed:
                rm = f"cd {APP} && rm -f -- " + " ".join(shlex.quote(r) for r in removed)
                head_img = await sandbox.retrying(lambda: head_img.run(shell=rm, disposable=False, timeout=120),
                                                  "removing files the PR deletes", log)
            if install and any(DEPENDENCY_FILES.search(c) for c in changed + removed):
                log("[tests] the PR changes dependencies: installing them again for head")
                head_img = await install_on(head_img, "installing the PR's dependencies", again=True)
            return {"base": img, "head": head_img}
        self.images = self.loop.run_until_complete(build())

    def run(self, jobs: list[tuple[str, str]], timeout: int = TEST_TIMEOUT) -> list[dict]:
        import asyncio

        from doppel.backends.nebius import OUTPUT_LIMIT

        def script(cmd: str) -> str:
            return (f"mkdir -p /tmp/dt && cd {self.app} && ({self.exports}{cmd}) > /tmp/dt/output.txt 2>&1; "
                    "echo $? > /tmp/dt/exit; cd /tmp/dt && tar czf - . | base64 -w0")

        async def one(code: str, cmd: str):
            return await self.sandbox.retrying(
                lambda: self.images[code].run(shell=script(cmd), files=self.files, disposable=True, timeout=timeout,
                                              truncate_output_at=OUTPUT_LIMIT),
                "running the tests in a sandbox", self.log, self.sem)

        async def go():
            outs = await asyncio.gather(*[one(code, cmd) for code, cmd in jobs])
            return [_untar(o.stdout or "", o.stderr or "") for o in outs]
        return self.loop.run_until_complete(go())

    def add_env(self, more: dict) -> None:
        """More settings for every later job (a repair between tries)."""
        import shlex
        self.exports += "".join(f"export {k}={shlex.quote(v)}; " for k, v in more.items())

    def close(self) -> None:
        self.loop.close()


def _untar(stdout: str, stderr: str) -> dict:
    """A sandbox job's result folder, sent back as base64 of a tar.gz on its last stdout line."""
    try:
        data = base64.b64decode(stdout.strip().splitlines()[-1] if stdout.strip() else "")
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
            return {Path(m.name).name: tar.extractfile(m).read().decode("utf-8", "replace")
                    for m in tar.getmembers() if m.isfile()}
    except Exception as e:  # noqa: BLE001
        return {"output.txt": f"(could not read this job's results: {type(e).__name__}: {e})\n{stderr[-2000:]}",
                "exit": "unreadable"}


PYTHON_VERSION = re.compile(r"^3\.\d{1,2}$")
PYTHON_VENV = "/opt/doppel-python"


def open_session(backend: str, base: Path, head: Path, install: str, log=lambda m: None, python: str = "",
                 extra_env: dict | None = None, workdir: str = ""):
    """python: a version ("3.8": installed in the sandbox with uv, on the standard image) or, locally, an
    interpreter path (its venv runs the tests). Empty: the image's Python; locally, your environment."""
    if backend == "local":
        return LocalSession(base, head, install, log, python=python, extra_env=extra_env, workdir=workdir)
    return NebiusSession(base, head, install, log=log, extra_env=extra_env, python=python, workdir=workdir)


# ---------------------------------------------------------------- 3b. planning: shards and confirmation

SHARD_FILES, FILES_PER_SHARD, MAX_SHARDS, MAX_CONFIRM = 30, 25, 8, 200


def runner_kind(cmd: str) -> str:
    if re.search(r"\bpytest\b", cmd):
        return "pytest"
    if re.search(r"manage\.py\s+test\b", cmd):
        return "django"
    if re.search(r"-m\s+unittest\b", cmd):
        return "unittest"
    return ""


def test_files(repo: Path, cmd: str) -> list[str]:
    """The test files a pytest command would run: under the paths it names, or anywhere in the repo."""
    import shlex
    try:
        words = shlex.split(cmd)
    except ValueError:
        return []
    after = words[words.index("pytest") + 1:] if "pytest" in words else []
    roots = [w for w in after if not w.startswith("-") and (repo / w.split("::")[0]).exists()]
    out = set()
    for root in roots or ["."]:
        start = repo / root
        files = [start] if start.is_file() else [*start.rglob("test_*.py"), *start.rglob("*_test.py")]
        for f in files:
            rel = f.relative_to(repo)
            if not {".venv", "venv", "node_modules", ".tox", "site-packages", ".git"} & set(rel.parts):
                out.add(rel.as_posix())
    return sorted(out)


def shards(repo: Path, cmd: str) -> list[str]:
    """Large pytest suites split by test file across sandboxes (whole files stay together, so tests that
    share a module's setup still run together). Small suites, and other runners, run whole."""
    import shlex
    if runner_kind(cmd) != "pytest":
        return [cmd]
    files = test_files(repo, cmd)
    if len(files) < SHARD_FILES:
        return [cmd]
    n = min(MAX_SHARDS, -(-len(files) // FILES_PER_SHARD))
    keep = _without_targets(repo, shlex.split(cmd), "pytest")
    return [" ".join(shlex.quote(w) for w in keep + files[k::n]) for k in range(n)]


