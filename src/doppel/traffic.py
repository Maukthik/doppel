def _without_targets(repo: Path, words: list[str], after: str) -> list[str]:
    """The command's words minus the test targets it names after `after` (paths, node ids, labels)."""
    if after not in words:
        return words
    k = words.index(after) + 1
    out, prev = words[:k], ""
    for w in words[k:]:
        takes_value = prev in VALUE_OPTIONS
        # Django's and unittest's positional words are all labels; pytest's are paths and node ids
        target = not w.startswith("-") and not takes_value and (
            after != "pytest" or "::" in w or w.endswith(".py") or (repo / w).exists())
        if not target:
            out.append(w)
        prev = w
    return out


def confirm_command(repo: Path, cmd: str, tests: list[str]) -> str:
    """The same command restricted to these tests (pytest node ids, unittest/Django dotted ids), or ""
    when the runner can't select tests by id."""
    import shlex
    kind = runner_kind(cmd)
    if not tests or len(tests) > MAX_CONFIRM or not kind:
        return ""
    try:
        words = shlex.split(cmd)
    except ValueError:
        return ""
    after = {"pytest": "pytest", "django": "test", "unittest": "unittest"}[kind]
    return " ".join(shlex.quote(w) for w in _without_targets(repo, words, after) + tests)


def merge(results: list[dict]) -> dict:
    """One world from its shards: file names made unique (process ids repeat across sandboxes)."""
    files: dict[str, str] = {}
    exits, outputs = [], []
    for k, r in enumerate(results):
        for name, text in r.items():
            if name.startswith(("traffic-", "outcomes-", "errors-")):
                files[f"{name.split('-', 1)[0]}-s{k}-{name.split('-', 1)[1]}"] = text
        exits.append(r.get("exit", "?").strip())
        outputs.append(r.get("output.txt", ""))
    worst = next((e for e in exits if e not in ("0",)), "0")
    return {**files, "exit": worst, "output.txt": "\n".join(outputs)}


# ---------------------------------------------------------------- 4. reading a world

def normalize_body(text: str, ctype: str):
    from doppel.runner import is_html, page_view
    value = text
    if "json" in (ctype or "") or (text[:1] in "[{" and text.strip()[-1:] in "]}"):
        try:
            value = json.loads(text)
        except ValueError:
            value = text
    elif is_html(ctype, text):
        value = page_view(text)
    return _strip_origin(value)


def _strip_origin(value):
    if isinstance(value, dict):
        return {k: _strip_origin(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_strip_origin(v) for v in value]
    if isinstance(value, str) and "://" in value:
        return IN_PROCESS_ORIGIN.sub("", value)
    return value


def read_world(files: dict) -> dict:
    """{"tests": {id: {"outcome", "requests": [...]}}, "exit", "output", "recorder_errors"}."""
    tests: dict[str, dict] = {}
    for name, text in sorted(files.items()):
        if name.startswith("traffic-"):
            for line in text.splitlines():
                try:
                    e = json.loads(line)
                except ValueError:
                    continue
                req = {"seq": e["seq"], "sig": f"{e['method']} {e['path']}" + (f"?{e['query']}" if e["query"] else ""),
                       "status": e["status"], "body": normalize_body(e.get("body", ""), e.get("type", "")),
                       "sent": e.get("sent", ""), "phase": e.get("phase", "")}
                tests.setdefault(e["test"], {"outcome": "unknown", "requests": []})["requests"].append(req)
    for name, text in sorted(files.items()):
        if name.startswith("outcomes-"):
            for line in text.splitlines():
                try:
                    e = json.loads(line)
                except ValueError:
                    continue
                t = tests.setdefault(e["test"], {"outcome": "unknown", "requests": []})
                if e["outcome"] in ("failed", "error"):
                    t["outcome"] = "failed"
                    t["message"] = e.get("message", "") or t.get("message", "")
                elif e["outcome"] == "skipped" and t["outcome"] != "failed":
                    t["outcome"] = "skipped"
                elif e["outcome"] == "passed" and t["outcome"] == "unknown":
                    t["outcome"] = "passed"
    for t in tests.values():
        t["requests"].sort(key=lambda r: r["seq"])
    errors = "".join(text for name, text in files.items() if name.startswith("errors-"))
    return {"tests": tests, "exit": files.get("exit", "?").strip(), "output": files.get("output.txt", ""),
            "recorder_errors": errors}


# ---------------------------------------------------------------- 5. comparing

def _align(a: list[dict], b: list[dict]):
    """Pairs (i, j) of requests with the same signature in order, plus the unmatched ones of each side."""
    sm = difflib.SequenceMatcher(a=[r["sig"] for r in a], b=[r["sig"] for r in b], autojunk=False)
    pairs, only_a, only_b = [], [], []
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            pairs += list(zip(range(i1, i2), range(j1, j2), strict=True))
        else:
            only_a += list(range(i1, i2))
            only_b += list(range(j1, j2))
    return pairs, only_a, only_b


def _leaf(path: str) -> str:
    return re.sub(r"\s*\((added|removed)\)$", "", path).rsplit(".", 1)[-1]


def _clean(path: str) -> str:
    return re.sub(r"\s*\((added|removed)\)$", "", path)


def noise(a: dict, a2: dict) -> dict:
    """S2: what differs between two runs of the same code. {"flaky": tests whose outcome differed,
    "unstable": tests whose requests differed, "paths": {(test, i): noisy paths}, "status": {(test, i)},
    "keys": leaf names noisy anywhere}."""
    out = {"flaky": set(), "unstable": set(), "paths": {}, "status": set(), "keys": set()}
    for test, ta in a["tests"].items():
        tb = a2["tests"].get(test)
        if tb is None or ta["outcome"] != tb["outcome"]:
            out["flaky"].add(test)
            continue
        if [r["sig"] for r in ta["requests"]] != [r["sig"] for r in tb["requests"]]:
            out["unstable"].add(test)
            continue
        for i, (ra, rb) in enumerate(zip(ta["requests"], tb["requests"], strict=True)):
            if ra["status"] != rb["status"]:
                out["status"].add((test, i))
            paths = changed_paths(ra["body"], rb["body"], limit=10_000)
            if paths:
                out["paths"][(test, i)] = {_clean(p) for p in paths}
                out["keys"] |= {_leaf(p) for p in paths if _leaf(p) and not _leaf(p).isdigit()}
    return out


def _mask(value, paths: set[str], keys: set[str], prefix: str = ""):
    if not prefix and "(whole body)" in paths:   # a plain-text body that differs between identical runs
        return "(noise)"
    if isinstance(value, dict):
        return {k: "(noise)" if (prefix + k in paths or k in keys)
                else _mask(v, paths, keys, f"{prefix}{k}.") for k, v in value.items()}
    if isinstance(value, list):
        return ["(noise)" if f"{prefix}{i}" in paths else _mask(v, paths, keys, f"{prefix}{i}.")
                for i, v in enumerate(value)]
    return "(noise)" if prefix.rstrip(".") in paths and prefix else value


def compare_worlds(a: dict, b: dict, nz: dict, excluded: set[str]) -> tuple[list[Finding], dict]:
    """Findings between base (a) and head (b), with noise and excluded tests left out."""
    findings: list[Finding] = []
    stats = {"tests": 0, "requests": 0, "new_tests": 0, "removed_tests": 0}
    for test, ta in sorted(a["tests"].items()):
        if test in excluded or test in nz["flaky"]:
            continue
        tb = b["tests"].get(test)
        if tb is None:
            stats["removed_tests"] += 1
            findings.append(Finding("test", test, 0, "(test)", "this test no longer exists in head", ta["outcome"],
                                    "(missing)"))
            continue
        stats["tests"] += 1
        stats["requests"] += len(ta["requests"])
        broke = ta["outcome"] == "passed" and tb["outcome"] == "failed"
        if test in nz["unstable"]:
            if broke:
                findings.append(_test_failed(test, tb))
            continue
        pairs, only_a, only_b = _align(ta["requests"], tb["requests"])
        if broke and pairs:
            # the test stopped at a failing assertion: whatever base sent after head's last matched request
            # was never going to be sent. That is the test ending early, not the app behaving differently.
            last = max(i for i, _ in pairs)
            only_a = [i for i in only_a if i < last]
        elif broke:
            only_a = []
        local: list[Finding] = []
        for i, j in pairs:
            ra, rb = ta["requests"][i], tb["requests"][j]
            if ra["status"] != rb["status"] and (test, i) not in nz["status"]:
                crashed = rb["status"] == 0 or rb["status"] >= 500
                local.append(Finding("error" if crashed and not (ra["status"] == 0 or ra["status"] >= 500)
                                        else "status", test, i, ra["sig"], f"status {ra['status']} -> {rb['status']}",
                                        ra["status"], rb["status"]))
                continue
            noisy = nz["paths"].get((test, i), set())
            ba, bb = _mask(ra["body"], noisy, nz["keys"]), _mask(rb["body"], noisy, nz["keys"])
            paths = changed_paths(ba, bb, limit=50)
            if paths:
                from doppel.diff import _at
                shown = [_clean(p) for p in paths[:4]]
                local.append(Finding("body", test, i, ra["sig"], "changed: " + summarize_paths(paths),
                                        {p: _at(ba, p) for p in shown}, {p: _at(bb, p) for p in shown}))
        for j in only_b:
            rb = tb["requests"][j]
            local.append(Finding("request", test, j, rb["sig"], "a request only the head run made",
                                    "(not sent)", rb["status"]))
        for i in only_a:
            ra = ta["requests"][i]
            local.append(Finding("request", test, i, ra["sig"], "a request only the base run made",
                                    ra["status"], "(not sent)"))
        responses = [f for f in local if f.kind in ("error", "status", "body")]
        if broke and responses:
            # the failing test is evidence about the response change that broke it: one change, judged once
            cause = max(responses, key=lambda f: f.step)
            cause.detail += " (the base branch's test fails on this)"
        elif broke:
            local.insert(0, _test_failed(test, tb))
        findings += local
    stats["new_tests"] = len(set(b["tests"]) - set(a["tests"]))
    return findings, stats


# ---------------------------------------------------------------- 6. the check, with its safeguards

RUN_SPECIFIC = re.compile(r"0x[0-9a-fA-F]{6,}|(?:[A-Za-z]:)?[\\/][^\s'\"]*?doppel-tests-[^\\/\s]+[\\/]job\d+[\\/]|"
                          r"/app/(?=[^\s'\"]+\.py)")


def scrub(text: str) -> str:
    """Remove what is specific to one run from a message: job folders, the sandbox's /app/, memory addresses."""
    return RUN_SPECIFIC.sub(lambda m: "0x…" if m.group(0).startswith("0x") else "", text)


def _test_failed(test: str, tb: dict) -> Finding:
    """A base test that fails on head with no response difference to explain it: its own failure message is
    the evidence."""
    message = scrub(tb.get("message") or "").strip()
    errors = [ln[1:].strip() for ln in message.splitlines() if ln.startswith("E ")]   # pytest's "E   ..." lines
    last = ("; ".join(errors[:3]) if errors else (message.splitlines()[-1] if message else
                                                  "(no failure message recorded)"))[:300]
    return Finding("test", test, 0, "(test outcome)", f"the test passed on base and fails on head: {last}",
                   "passed", "failed")


def _key(f: Finding) -> tuple:
    """What has to happen again for a difference to be confirmed. A failing test is the same failure whatever
    its message says (messages carry run-specific paths and addresses)."""
    if f.kind == "test":
        return f.kind, f.persona, f.request
    return f.kind, f.persona, f.request, f.detail.replace(" (the base branch's test fails on this)", "")


def confirm(session, base: Path, test: str, findings: list[Finding], a: dict, b: dict, nz: dict,
            excluded: set[str], log=lambda m: None) -> tuple[list[Finding], dict]:
    """S5: run only the tests that showed a difference again, on base and on head, and keep a difference only
    if it shows up the same way again. A difference that came from rare nondeterminism the A/A run happened to
    miss does not survive two independent runs."""
    tests = sorted({f.persona for f in findings})
    cmd = confirm_command(base, test, tests)
    if not findings:
        return findings, {"ran": False, "reason": "no differences"}
    if not cmd:
        why = (f"{len(tests)} tests differ (more than {MAX_CONFIRM})" if len(tests) > MAX_CONFIRM
               else "the test runner can't select single tests")
        log(f"[tests] differences not re-checked: {why}")
        return findings, {"ran": False, "reason": why}
    log(f"[tests] confirming {len(findings)} difference(s): rerunning {len(tests)} test(s) on base and head")
    again_a, again_b = (read_world(r) for r in session.run([("base", cmd), ("head", cmd)]))
    if not again_a["tests"]:
        log("[tests] the confirmation run selected no tests; keeping the differences unconfirmed")
        return findings, {"ran": False, "reason": "the confirmation run selected no tests"}
    # base, base again and the confirmation base together say what varies; then compare the reruns
    nz2 = noise(a, again_a)
    merged = {"flaky": nz["flaky"] | nz2["flaky"], "unstable": nz["unstable"] | nz2["unstable"],
              "status": nz["status"] | nz2["status"], "keys": nz["keys"] | nz2["keys"],
              "paths": {k: nz["paths"].get(k, set()) | nz2["paths"].get(k, set())
                        for k in set(nz["paths"]) | set(nz2["paths"])}}
    seen_again = {_key(f) for f in compare_worlds(again_a, again_b, merged, excluded)[0]}
    kept = [f for f in findings if _key(f) in seen_again and f.persona not in merged["flaky"]]
    gone = [f for f in findings if f not in kept]
    if gone:
        log(f"[tests] {len(gone)} difference(s) did not happen again and were dropped as noise")
    # kept for audit, never as findings: a difference that depends on test order (state left by earlier tests)
    # can also fail to come back when only its tests rerun, and a reader should be able to tell the two apart
    unconfirmed = [{"kind": f.kind, "test": f.persona, "request": f.request, "detail": f.detail[:300],
                    "base": str(f.base)[:300], "head": str(f.head)[:300]} for f in gone[:50]]
    return kept, {"ran": True, "tests": len(tests), "dropped": len(gone), "unconfirmed": unconfirmed}


RECORDED = {"werkzeug/Flask test client": r"test_client\(|werkzeug\.test|flask\.testing",
            "Django test client": r"django\.test|self\.client\.|APIClient|async_client",
            "Starlette/FastAPI TestClient": r"(starlette|fastapi)\.testclient", "httpx": r"\bhttpx\b",
            "requests (to a local server)": r"\bimport requests\b|from requests", "Tornado": r"tornado\.testing",
            "aiohttp test client": r"aiohttp\.test_utils|aiohttp_client", "WebTest": r"\bwebtest\b",
            "Falcon": r"falcon\.testing"}
NOT_RECORDED = {"websockets": r"websocket", "a browser (Selenium/Playwright)": r"selenium|playwright",
                "urllib / http.client": r"urllib\.request|http\.client", "gRPC": r"\bgrpc\b",
                "a mocked app (responses / respx / requests-mock)": r"\bresponses\b|\brespx\b|requests_mock"}


def why_nothing_recorded(repo: Path) -> str:
    """What the test files actually use to talk to the app, so "nothing recorded" comes with a reason."""
    text = ""
    for f in sorted(repo.rglob("*.py"))[:2000]:
        rel = f.relative_to(repo)
        if is_test_file(rel.as_posix()) and not {".venv", "venv", "node_modules", ".tox"} & set(rel.parts):
            text += f.read_text("utf-8", errors="replace")[:20000]
    seen = [name for name, rx in RECORDED.items() if re.search(rx, text)]
    unseen = [name for name, rx in NOT_RECORDED.items() if re.search(rx, text)]
    if unseen and not seen:
        return f"The tests talk to the app through {', '.join(unseen)}, which Doppel does not record."
    if seen:
        return (f"The tests use {', '.join(seen)}, but none of their requests reached the app through it (the app "
                "may be mocked, or the requests go to another host)"
                + (f"; they also use {', '.join(unseen)}, which Doppel does not record." if unseen else "."))
    return "The tests don't seem to send HTTP requests at all (they may test functions directly)."


def _passed_or_failed(world: dict) -> tuple[int, int]:
    outcomes = [t["outcome"] for t in world["tests"].values()]
    return sum(o == "passed" for o in outcomes), sum(o == "failed" for o in outcomes)


PLACEHOLDER = "doppel-placeholder-3f9c2b7e8a1d4c6f9b0e5a7d2c8f1b4e"
SERVICE_SETTING = re.compile(r"(_URL|_URI|_DSN|_HOST|_PORT|_ADDR|_ENDPOINT|_SERVER)$")
MISSING_SETTING = [re.compile(p) for p in (
    r"You must set the ([A-Z][A-Z0-9_]{2,}) environment variable",                 # redash
    r"Set the ([A-Z][A-Z0-9_]{2,}) environment variable",                          # django-environ
    r"[Ee]nvironment variable ['\"]?([A-Z][A-Z0-9_]{2,})['\"]? (?:is )?(?:not set|missing|required)",
    r"environ\[['\"]([A-Z][A-Z0-9_]{2,})['\"]\][\s\S]{0,400}?KeyError: ['\"]\1['\"]",
    r"(?m)^(?:E\s+|\s*)([A-Z][A-Z0-9_]{2,})\s*\n(?:E\s+|\s*)Field required \[type=missing",  # pydantic settings
)]


def placeholder_settings(output: str, have: dict) -> dict:
    """Settings the tests refused to start without, each set to a placeholder: a secret or a flag can be any
    value in a test run (redash: 'You must set the REDASH_COOKIE_SECRET environment variable'). An address
    (..._URL, ..._HOST, ...) is never invented: it names a service, and the stop says so."""
    names = {m.group(1) for pat in MISSING_SETTING for m in pat.finditer(output or "")}
    return {n: PLACEHOLDER for n in sorted(names) if n not in have and not SERVICE_SETTING.search(n)}


def check(base: str | Path, head: str | Path, backend: str = "nebius", test: str | None = None,
          install: str | None = None, log=lambda m: None, runner=None, python: str = "",
          deselect: list[str] | None = None) -> dict:
    """python: see open_session. deselect: pytest node ids to leave out in every world (a benchmark hides
    the test that was written after a bug was found)."""
    """`runner(backend, base, head, install, log)` opens a session (tests inject one); default LocalSession or
    NebiusSession."""
    """Run the app's tests in three worlds and compare. Raises NotComparable (with the reason) when a
    safeguard says the comparison would be meaningless. Returns {"findings", "stats", "excluded",
    "flaky", "unstable", "noise_keys", "detected", "worlds"}."""
    base, head = Path(base).resolve(), Path(head).resolve()
    found = detect(base)
    plan = found.get("plan") or {}
    workdir = plan.get("workdir", "") if not test else ""   # a command you give runs where you point
    code = base / workdir if workdir else base               # where the tests and the manifest are
    test = test or found["test"]
    install = found["install"] if install is None else install
    if not test:
        below = suites_below(base)
        if below:
            raise NotComparable("no test suite in this folder, but these subfolders have one: "
                                + ", ".join(below) + ". Point --base and --head at that folder (for a monorepo "
                                "package), or give the command with --command.")
        raise NotComparable("no test suite found (no tox.ini, CI test step, Makefile test target, noxfile, pytest "
                            "configuration, manage.py or test files): test mode needs the app's own tests. Use "
                            "the HTTP twin (`doppel run` with a doppel.toml) instead.")
    log(f"[tests] test command: {test}   (from {found['source']['test'] if test == found['test'] else 'you'})")
    if workdir:
        log(f"[tests] running in {workdir}/ (the whole repo is there too)")
    if backend != "local" and install:
        log(f"[tests] install: {install[:140]}   (from {found['source']['install']})")
    command_env, test = split_env(test)
    extra_env = {**(plan.get("env") or {}), **command_env}
    if extra_env:
        log(f"[tests] environment for every world: {extra_env}")
    services = plan.get("services") or []
    unmet = (f" The project's CI starts services Doppel doesn't start yet: {', '.join(services)}."
             if services else "")
    if deselect and runner_kind(test) == "pytest":
        import shlex
        test = test + " " + " ".join(shlex.quote(f"--deselect={d}") for d in deselect)   # one word: never split
    session = runner(backend, base, head, install, log) if runner else open_session(backend, base, head, install,
                                                                                   log, python, extra_env, workdir)
    try:
        plan = shards(code, test)
        if len(plan) > 1:
            log(f"[tests] {len(test_files(code, test))} test files: split across {len(plan)} sandboxes per world")
        log(f"[tests] running `{test}` in 3 worlds (base, base again, head)")
        k = len(plan)
        for attempt in range(3):
            runs = session.run([(code, cmd) for code in ("base", "base", "head") for cmd in plan])
            worlds = {w: read_world(merge(runs[i * k:(i + 1) * k])) for i, w in enumerate(WORLDS)}
            a, a2, b = worlds["A"], worlds["A2"], worlds["B"]
            passed, failed = _passed_or_failed(a)
            wanted = {} if passed or attempt == 2 else placeholder_settings(a["output"], extra_env)
            if not wanted or not hasattr(session, "add_env"):
                break
            log(f"[tests] the tests need {', '.join(wanted)} set: using placeholder values, running again")
            extra_env.update(wanted)
            session.add_env(wanted)
        # S1: the base has to have run
        if passed + failed == 0:
            raise NotComparable(f"the test command ran no test on the unchanged code (exit {a['exit']}).{unmet} "
                                "Its output:\n" + a["output"][-3000:])
        if failed > MAX_FAILING_SHARE * (passed + failed):
            raise NotComparable(f"{failed} of {passed + failed} tests fail on the unchanged code here, so this "
                                "environment is not the one the tests expect (a missing service, env var or "
                                f"dependency).{unmet} Output:\n" + a["output"][-3000:])
        failing_on_base = {t for w in (a, a2) for t, v in w["tests"].items() if v["outcome"] == "failed"}
        # S2: noise from two runs of the same code
        nz = noise(a, a2)
        # S4: something to compare
        requests = sum(len(t["requests"]) for t in a["tests"].values())
        if requests == 0:
            raise NotComparable(f"the tests ran ({passed} passed) but sent no request through a test client Doppel "
                                "records, so there is no traffic to compare. " + why_nothing_recorded(code) +
                                " The tests' own pass/fail still applies; for behavior checks use the HTTP twin.")
        findings, stats = compare_worlds(a, b, nz, failing_on_base)
        # S5: a difference counts only if it happens again
        findings, confirmed = confirm(session, code, test, findings, a, b, nz, failing_on_base, log)
        stats["confirmation"] = confirmed
    finally:
        session.close()
    stats.update(passed=passed, failing_on_base=len(failing_on_base), flaky=len(nz["flaky"]),
                 unstable=len(nz["unstable"]), noisy_keys=len(nz["keys"]), recorded_requests=requests)
    if a["recorder_errors"] or b["recorder_errors"]:
        log("[tests] note: the recorder reported problems (they never affect the tests):\n"
            + (a["recorder_errors"] or b["recorder_errors"])[-1500:])
    log(f"[tests] {passed} tests passed on base; {requests} requests recorded; {len(nz['flaky'])} flaky, "
        f"{len(nz['unstable'])} with varying requests, {len(nz['keys'])} noisy field name(s); "
        f"{len(findings)} difference(s)")
    return {"findings": findings, "stats": stats, "excluded": sorted(failing_on_base), "flaky": sorted(nz["flaky"]),
            "unstable": sorted(nz["unstable"]), "noise_keys": sorted(nz["keys"]), "detected": found,
            "test": test, "worlds": {w: {"exit": v["exit"], "tests": len(v["tests"])} for w, v in worlds.items()}}


# ---------------------------------------------------------------- 7. the report

def report(result: dict, judged: dict | None = None) -> str:
    from doppel.report import markdown
    st = result["stats"]
    body = markdown(result["findings"], st["tests"], st["requests"], judged, who="test")
    left_out = []
    if result["excluded"]:
        left_out.append(f"{len(result['excluded'])} failing on unchanged code")
    if result["flaky"]:
        left_out.append(f"{len(result['flaky'])} flaky (passed once, failed once on unchanged code)")
    if result["unstable"]:
        left_out.append(f"{len(result['unstable'])} compared on outcome only (their requests vary between "
                        "identical runs)")
    lines = [body.rstrip(), "",
             f"<sub>Test mode: `{result['test']}` (from {result['detected']['source']['test']}) ran on base twice and "
             f"on head, with the base branch's tests in both. {st['passed']} tests passed on base. "
             + (f"Left out: {'; '.join(left_out)}. " if left_out else "")
             + (f"Ignored as noise (they differ between two runs of the same code): "
                f"{', '.join(f'`{k}`' for k in result['noise_keys'][:12])}. " if result["noise_keys"] else "")
             + (f"{st['new_tests']} test(s) the PR adds have no baseline and are not compared. " if st["new_tests"]
                else "") + _confirmation_line(st.get("confirmation") or {}) + "</sub>"]
    return "\n".join(lines) + "\n"


def _confirmation_line(c: dict) -> str:
    if c.get("ran"):
        return (f"Every difference was re-checked by rerunning its {c['tests']} test(s) on base and head"
                + (f"; {c['dropped']} that did not happen again were dropped as noise." if c.get("dropped") else "."))
    if c.get("reason") and c["reason"] != "no differences":
        return f"Differences were not re-checked ({c['reason']})."
    return ""


def not_comparable(reason: str) -> str:
    return ("## Doppel: couldn't compare this PR (test mode)\n\n"
            "A safeguard stopped the check before any verdict, because the comparison would not mean anything:\n\n"
            + "\n".join(f"> {ln}" if ln.strip() else ">" for ln in reason.strip().splitlines()[:40]) + "\n")
